#!/usr/bin/env python3
"""main_mixedcode_benchmark.py

Evaluate DetectCodeGPT NPR on the mixed-code benchmark generated by
code-selection/generate_mixedcode_benchmark.py.

This script treats main.py as a library. It reuses:
  - main.perturb_texts and main.setup_args
  - baselines.rank.get_rank / get_ranks
  - baselines.utils.preprocessing.preprocess_and_save
  - baselines.utils.loadmodel.load_base_model_and_tokenizer

Input benchmark layout:

  mixedcode_benchmarks/<GEN_MODEL>/
    type01_110/
      mixed_code_001.py
      mixed_code_001.json
      ...
    type02_120/
      mixed_code_001.py
      mixed_code_001.json
      ...

Each JSON sidecar contains per-function metadata with body_start_char/body_end_char.
The detector input is exactly:

  body_text = mixed_code[body_start_char:body_end_char]

That excludes the function signature and leading docstring/prompt.

Typical usage from code-detection/:

  CUDA_VISIBLE_DEVICES=0 python main_mixedcode_benchmark.py \
    --benchmark_root ../code-selection/mixedcode_benchmarks/starcoder2-7b \
    --base_model_name bigcode/starcoder2-7b \
    --output_name mixedcode_starcoder2-7b_n50

Fast re-aggregation without rescoring:

  python main_mixedcode_benchmark.py \
    --benchmark_root ../code-selection/mixedcode_benchmarks/starcoder2-7b \
    --load_cached_results ../logs/results_cache_main_mixedcode_benchmark_...pkl \
    --aggregate max
"""


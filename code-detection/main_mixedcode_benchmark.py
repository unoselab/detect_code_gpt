def main() -> None:
    parser = argparse.ArgumentParser(
        description="Evaluate DetectCodeGPT NPR on generated mixed-code benchmark files."
    )
    parser.add_argument("--benchmark_root", required=True,
                        help="Root containing type*/mixed_code_*.py and .json files.")
    parser.add_argument("--base_model_name", type=str, default="bigcode/starcoder2-7b")
    parser.add_argument("--n_perturbation", type=int, default=50,
                        help="Perturbed copies per chunk.")
    parser.add_argument("--pct_words_masked", type=float, default=0.5)
    parser.add_argument("--span_length", type=int, default=2)
    parser.add_argument("--chunk_size", type=int, default=10,
                        help="Batch size inside perturb_texts. Keep even for space+newline split.")
    parser.add_argument("--n_perturbation_rounds", type=int, default=1)
    parser.add_argument("--perturb_type", type=str, default="random-insert-space+newline")
    parser.add_argument("--chunk_len", type=int, default=128,
                        help="Whitespace-token chunk length used within each function body.")
    parser.add_argument("--min_chunk_tokens", type=int, default=1,
                        help="Chunks below this are low-confidence and not scored.")
    parser.add_argument("--aggregate", choices=["weighted_mean", "mean", "max"], default="weighted_mean")
    parser.add_argument("--device", type=str, default="cuda")
    parser.add_argument("--cache_dir", type=str, default="~/.cache/huggingface/hub")
    parser.add_argument("--output_name", type=str, default="mixedcode_benchmark")
    parser.add_argument("--output_csv", type=str, default=None)
    parser.add_argument("--chunk_csv", type=str, default=None)
    parser.add_argument("--results_cache", type=str, default=None)
    parser.add_argument("--load_cached_results", type=str, default=None,
                        help="Skip scoring and load cached per-function chunk results.")
    parser.add_argument("--limit_files", type=int, default=None,
                        help="Debug: only load first N JSON sidecars.")
    parser.add_argument("--limit_functions", type=int, default=None,
                        help="Debug: only score first N function bodies.")
    parser.add_argument("--preview", action="store_true",
                        help="Print detector body_text inputs before scoring.")
    parser.add_argument("--count_only", action="store_true",
                        help="Load benchmark and print counts without model/scoring.")
    cli = parser.parse_args()

    benchmark_root = Path(os.path.expanduser(cli.benchmark_root))
    output_csv = Path(os.path.expanduser(
        cli.output_csv or f"../logs/npr_scores_main_mixedcode_benchmark_{cli.output_name}.csv"
    ))
    chunk_csv = Path(os.path.expanduser(
        cli.chunk_csv or f"../logs/npr_chunks_main_mixedcode_benchmark_{cli.output_name}.csv"
    ))
    cache_path = Path(os.path.expanduser(
        cli.results_cache or f"../logs/results_cache_main_mixedcode_benchmark_{cli.output_name}.pkl"
    ))

    if cli.load_cached_results is not None:
        load_cache = Path(os.path.expanduser(cli.load_cached_results))
        logger.info(f"Loading cached mixed-code results from {load_cache}; skipping model/scoring")
        with load_cache.open("rb") as f:
            results = pickle.load(f)
        summarize_and_save(results, output_csv, chunk_csv, cli.aggregate)
        return

    examples = load_mixedcode_functions(
        benchmark_root,
        limit_files=cli.limit_files,
        limit_functions=cli.limit_functions,
    )

    if not examples:
        raise RuntimeError(f"No function bodies found under {benchmark_root}")

    print("=" * 80)
    print("main_mixedcode_benchmark.py")
    print("=" * 80)
    print(f"benchmark_root       : {benchmark_root}")
    print(f"function bodies      : {len(examples)}")
    print(f"base_model_name      : {cli.base_model_name}")
    print(f"device               : {cli.device}")
    print(f"chunk_len            : {cli.chunk_len}")
    print(f"min_chunk_tokens     : {cli.min_chunk_tokens}")
    print(f"aggregate            : {cli.aggregate}")
    print(f"n_perturbation       : {cli.n_perturbation}")
    print(f"perturb_type         : {cli.perturb_type}")
    print(f"output_csv           : {output_csv}")
    print(f"chunk_csv            : {chunk_csv}")
    print(f"results_cache        : {cache_path}")
    print("=" * 80)

    if cli.preview:
        preview_examples(examples, n=min(5, len(examples)))

    if cli.count_only:
        by_bucket: Dict[str, Dict[str, int]] = {}
        for ex in examples:
            b = ex["benchmark_type"]
            by_bucket.setdefault(b, {"HWC": 0, "AGC": 0})
            by_bucket[b][ex["role"]] = by_bucket[b].get(ex["role"], 0) + 1
        print("\nCounts by bucket:")
        for b in sorted(by_bucket):
            print(f"  {b}: HWC={by_bucket[b].get('HWC', 0)} AGC={by_bucket[b].get('AGC', 0)}")
        return

    # Build args required by the imported main.py / baseline helpers.
    args = build_full_args(cli)
    logger.info(f"Before model load: CUDA_VISIBLE_DEVICES={os.environ.get('CUDA_VISIBLE_DEVICES')}, args.DEVICE={args.DEVICE}")

    cache_dir, _, _ = preprocess_and_save(args)
    model_config: Dict[str, Any] = {"cache_dir": cache_dir}

    logger.info("Loading base scoring model...")
    model_config = load_base_model_and_tokenizer(args, model_config)

    results: List[Dict[str, Any]] = []
    for ex in tqdm(examples, desc="Scoring function bodies"):
        chunks = score_body(
            ex["body_text"],
            args=args,
            model_config=model_config,
            k=cli.n_perturbation,
            chunk_len=cli.chunk_len,
            min_chunk_tokens=cli.min_chunk_tokens,
        )
        r = dict(ex)
        # Do not keep body_text in cache/CSV unless needed; reduces pickle size a bit.
        r.pop("body_text", None)
        r["chunks"] = chunks
        results.append(r)

    cache_path.parent.mkdir(parents=True, exist_ok=True)
    with cache_path.open("wb") as f:
        pickle.dump(results, f)
    logger.info(f"Cached per-function chunk results to: {cache_path}")
    logger.info(f"To re-aggregate without rescoring: --load_cached_results {cache_path}")

    torch.cuda.empty_cache()
    summarize_and_save(results, output_csv, chunk_csv, cli.aggregate)



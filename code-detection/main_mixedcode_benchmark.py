def chunk_whitespace(text: str, chunk_len: int) -> List[Tuple[str, int, int, int]]:
    """Split text into split-space chunks.

    Returns list of:
      (chunk_text, n_tokens, start_token_in_body, end_token_in_body)
    """
    toks = text.split(" ")
    out: List[Tuple[str, int, int, int]] = []
    for start in range(0, len(toks), chunk_len):
        ct = toks[start:start + chunk_len]
        out.append((" ".join(ct), len(ct), start, start + len(ct)))
    return out


def score_chunk(chunk_text: str, args: argparse.Namespace, model_config: Dict[str, Any], k: int) -> Tuple[float, float, float]:
    """Per-chunk NPR = mean(perturbed log-rank) / original log-rank."""
    orig_logrank = get_rank(chunk_text, args, model_config, log=True)
    p_texts = perturb_texts([chunk_text for _ in range(k)], args, model_config)
    p_ranks = get_ranks(p_texts, args, model_config, log=True)
    valid = [r for r in p_ranks if not math.isnan(r)]
    mean_p = float(np.mean(valid)) if valid else float("nan")
    npr = mean_p / orig_logrank if orig_logrank else float("nan")
    return npr, orig_logrank, mean_p


def score_body(
    body_text: str,
    args: argparse.Namespace,
    model_config: Dict[str, Any],
    k: int,
    chunk_len: int,
    min_chunk_tokens: int,
) -> List[Dict[str, Any]]:
    """Score one function body and return per-chunk dictionaries."""
    chunks: List[Dict[str, Any]] = []
    if not body_text.strip():
        return chunks

    for chunk_idx, (chunk_text, n_tok, start_tok, end_tok) in enumerate(chunk_whitespace(body_text, chunk_len)):
        if n_tok < min_chunk_tokens or not chunk_text.strip():
            chunks.append({
                "chunk_idx": chunk_idx,
                "start_token_body": start_tok,
                "end_token_body": end_tok,
                "n_tokens": n_tok,
                "low_conf": True,
                "npr": float("nan"),
                "orig_logrank": float("nan"),
                "mean_p_logrank": float("nan"),
            })
            continue

        npr, orig_lr, mean_p = score_chunk(chunk_text, args, model_config, k)
        chunks.append({
            "chunk_idx": chunk_idx,
            "start_token_body": start_tok,
            "end_token_body": end_tok,
            "n_tokens": n_tok,
            "low_conf": False,
            "npr": npr,
            "orig_logrank": orig_lr,
            "mean_p_logrank": mean_p,
        })
    return chunks


def aggregate_npr(chunks: List[Dict[str, Any]], method: str) -> float:
    """Aggregate per-chunk NPR into one function-body score."""
    valid = [c for c in chunks if (not c["low_conf"]) and (not math.isnan(c["npr"]))]
    if not valid:
        return float("nan")
    if method == "mean":
        return float(np.mean([c["npr"] for c in valid]))
    if method == "max":
        return float(max(c["npr"] for c in valid))

    # weighted_mean
    wsum = sum(c["npr"] * c["n_tokens"] for c in valid)
    tsum = sum(c["n_tokens"] for c in valid)
    return float(wsum / tsum) if tsum else float("nan")


def n_scored(chunks: List[Dict[str, Any]]) -> int:
    return sum(1 for c in chunks if (not c["low_conf"]) and (not math.isnan(c["npr"])))


def n_lowconf(chunks: List[Dict[str, Any]]) -> int:
    return sum(1 for c in chunks if c["low_conf"])


